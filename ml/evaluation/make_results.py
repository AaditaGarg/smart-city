"""Assemble reports/RESULTS.md from the generated CSV/JSON files (no hand-typed numbers).

    python -m ml.evaluation.make_results
"""
from __future__ import annotations

import json

import pandas as pd

from ml.config import ROOT

from .common import df_to_md

T, F = ROOT / "reports" / "tables", ROOT / "reports" / "figures"


def section(task: str, title: str) -> str:
    csv, js = T / f"{task}_test_metrics.csv", T / f"{task}_test_summary.json"
    if not (csv.exists() and js.exists()):
        return f"## {title}\n\n_Not evaluated yet - run `python -m ml.evaluation.evaluate_yolo --task {task}`._\n"
    s = json.loads(js.read_text())
    out = [f"## {title}", "",
           f"Weights `{s['weights']}` ({s['weights_mb']} MB), trained for {s['epochs_trained']} epochs, "
           f"image size {s['imgsz']}, evaluated on the held-out **{s['split']}** split "
           f"({s['images_evaluated']} images) on `{s['device']}`.", "",
           df_to_md(pd.read_csv(csv)), ""]
    if s["low_support_classes"]:
        out += [f"Low-confidence classes (fewer than 30 test instances): {', '.join(s['low_support_classes'])}.", ""]
    for dev, l in s["latency_ms_per_image"].items():
        out.append(f"- Latency on `{dev}` (batch 1, includes image loading and NMS): mean {l['mean_ms']:.1f} ms, "
                   f"median {l['median_ms']:.1f} ms, p95 {l['p95_ms']:.1f} ms (~{l['fps_from_mean']:.1f} FPS), n={l['n_images']}.")
    out += ["", f"![confusion matrix](figures/{task}_test_confusion_matrix_normalized.png)",
            f"![training curves](figures/{task}_training_curves.png)",
            f"![predictions](figures/{task}_test_predictions.png)", ""]
    return "\n".join(out)


def congestion_section() -> str:
    csv = T / "congestion_metrics_table.csv"
    if not csv.exists():
        return "## Congestion estimation\n\n_Not evaluated yet._\n"
    m = json.loads((T / "congestion_metrics.json").read_text())
    return "\n".join(["## Congestion estimation (proxy target)", "",
                      "Target = index computed from ANNOTATED vehicles (count + image coverage); the model predicts it from "
                      "detector outputs. Fitted on the val split, scored on test. It measures how well detections reproduce "
                      f"annotated density, not human-rated congestion. Selected model: {m['selected_model']} "
                      f"(n_val={m['n_val']}, n_test={m['n_test']}).", "",
                      df_to_md(pd.read_csv(csv)), "", "![congestion](figures/congestion_evaluation.png)", ""])


def main():
    body = ["# Results", "", "_Generated by `ml/evaluation/make_results.py` from files in `reports/`._", "",
            section("vehicle", "Vehicle detection (KITTI)"), section("road_damage", "Road damage detection (RDD2022 India)"),
            congestion_section()]
    (ROOT / "reports" / "RESULTS.md").write_text("\n".join(body))
    print("wrote reports/RESULTS.md")


if __name__ == "__main__":
    main()
